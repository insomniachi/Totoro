<#
.SYNOPSIS
    Generates the animated icons' code from their Lottie files (*.json here), with LottieGen.

.DESCRIPTION
    Each <Name>.json becomes <Name>.cs: an IAnimatedVisualSource2 for an AnimatedIcon, like WinUI's own
    (AnimatedFindVisualSource...). Run it after changing a .json; both are checked in.

    For an AnimatedIcon, a Lottie file:
    - is drawn on a 48x48 canvas in white, the one color: it becomes the icon's Foreground (the color the AnimatedIcon
      sets, following the theme);
    - has markers named for the states it animates between, as WinUI's do: NormalToPointerOver_Start/_End,
      PointerOverToNormal_..., PointerOverToPressed_..., NormalToPressed_..., PressedToPointerOver_...,
      PressedToNormal_..., and Normal, PointerOver and Pressed;
    - uses no paths, only rectangles and ellipses: LottieGen draws paths with Win2D, which Totoro.UI doesn't use.

.EXAMPLE
    ./src/Totoro.UI/AnimatedVisuals/Generate.ps1
#>

$ErrorActionPreference = 'Stop'
Push-Location (Split-Path $PSScriptRoot -Parent | Split-Path -Parent | Split-Path -Parent)
try {
    # LottieGen is pinned in the repository's dotnet-tools.json.
    dotnet tool restore | Out-Null
    foreach ($lottie in Get-ChildItem $PSScriptRoot -Filter *.json) {
        dotnet lottiegen -InputFile $lottie.FullName -Language cs -Namespace Totoro.UI.AnimatedVisuals -Public `
            -GenerateColorBindings -WinUIVersion 3.0 -TestMode -OutputFolder $PSScriptRoot
        if ($LASTEXITCODE -ne 0) { throw "LottieGen failed on $($lottie.Name)." }

        # Its one color, bound as Color_FFFFFF, as the Foreground an AnimatedIcon sets; and marked generated, so the code
        # style rules leave it alone.
        $code = Join-Path $PSScriptRoot "$($lottie.BaseName).cs"
        $text = (Get-Content $code -Raw) -replace 'Color_FFFFFF', 'Foreground'
        Set-Content $code "// <auto-generated/> by Generate.ps1 from $($lottie.Name): change that and run it again.`r`n$text" -NoNewline
    }
}
finally {
    Pop-Location
}
